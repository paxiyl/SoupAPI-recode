"""Converts the mod's 1.21.4-style lang JSON into the .lang files 1.8.9 reads.

1.8.9's `Locale` loads `assets/<namespace>/lang/<xx_YY>.lang` as `key=value` lines; it has no
JSON loader, so every `text.autoconfig.soupapi.*` key in the JSON was invisible and the settings
screen showed raw keys. The JSONs stay as the source of truth; run this after editing one.

    python3 tools/lang_to_1_8_9.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
LANG = ROOT / 'src/main/resources/assets/soupapi/lang'

EXTRA = {
    # Keys the 1.8.9 port adds; they have no 1.21.4 counterpart.
    'en_US': {
        'key.categories.soupapi': 'SoupAPI',
        'key.soupapi.settings': 'Open SoupAPI settings',
        'soupapi.gui.open': 'Open',
        'soupapi.screen.soup_settings.title': 'SoupAPI settings',
        'key.soupapi.melee.next': 'Next melee weapon',
        'key.soupapi.melee.previous': 'Previous melee weapon',
        'key.soupapi.melee.inspect': 'Inspect melee weapon',
        'key.soupapi.melee.toggle': 'Toggle melee weapon',
    },
    'ru_RU': {
        'key.categories.soupapi': 'SoupAPI',
        'key.soupapi.settings': 'Открыть настройки SoupAPI',
        'soupapi.gui.open': 'Открыть',
        'soupapi.screen.soup_settings.title': 'Настройки SoupAPI',
        'key.soupapi.melee.next': 'Следующее оружие',
        'key.soupapi.melee.previous': 'Предыдущее оружие',
        'key.soupapi.melee.inspect': 'Осмотреть оружие',
        'key.soupapi.melee.toggle': 'Включить/выключить оружие',
    },
}

for src, dst in (('en_us.json', 'en_US.lang'), ('ru_ru.json', 'ru_RU.lang')):
    data = json.loads((LANG / src).read_text(encoding='utf-8'))
    data.update(EXTRA[dst[:-5]])
    lines = ['# Generated by tools/lang_to_1_8_9.py from ' + src + ' - do not edit by hand.']
    for key in sorted(data):
        if not key.strip():
            continue  # the JSON carries one blank key, which a .lang file cannot express
        value = str(data[key])
        if '=' in key or '\n' in value:
            raise SystemExit('key unusable in a .lang file: ' + key)
        lines.append(key + '=' + value)
    (LANG / dst).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('wrote', dst, len(data), 'entries')
